# Builds site.json for the 5-checkpoint campus from the overview drawing (6.jpg) and the gate drawings (1-5.jpg).
# Overview pixels -> metres: S m/px, origin at checkpoint 1 (Chaturathit), x east, y north.
#   py make_site.py   -> site.json
import json, math, os

S = 1.45                       # m per overview pixel (fits the uplink cable lengths on the drawing)
O = (375.8, 271.7)             # checkpoint 1 dot
def M(p): return [round((p[0] - O[0]) * S, 2), round(-(p[1] - O[1]) * S, 2)]
def Ms(ps): return [M(p) for p in ps]

# main campus road centre line (overview px)
ROAD_PX = [(120, 214), (200, 232), (290, 252), (375.8, 271.7), (470, 292), (560, 310), (660, 330), (761, 350),
           (864, 356), (972, 356), (1080, 340), (1184.5, 320), (1300, 285), (1430, 240)]
ROAD = Ms(ROAD_PX); ROAD_W = 9.0

def seglen(a, b): return math.dist(a, b)
CH = [0.0]
for a, b in zip(ROAD, ROAD[1:]): CH.append(CH[-1] + seglen(a, b))
def at(ch):
    """point + unit tangent on the road at chainage ch"""
    ch = max(0, min(CH[-1], ch))
    for i in range(len(ROAD) - 1):
        if CH[i + 1] >= ch:
            a, b = ROAD[i], ROAD[i + 1]; f = (ch - CH[i]) / (CH[i + 1] - CH[i])
            t = ((b[0] - a[0]) / seglen(a, b), (b[1] - a[1]) / seglen(a, b))
            return (a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f), t
def ch_of(px):
    """chainage of the road point nearest to an overview pixel"""
    p = M(px); best = (1e9, 0)
    for i in range(len(ROAD) - 1):
        a, b = ROAD[i], ROAD[i + 1]; dx, dy = b[0] - a[0], b[1] - a[1]; L2 = dx * dx + dy * dy
        f = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L2))
        q = (a[0] + dx * f, a[1] + dy * f); d = math.dist(p, q)
        if d < best[0]: best = (d, CH[i] + f * math.sqrt(L2))
    return best[1]
def strip(x0, x1, side, off, depth, step=6):
    """polygon following the road between two overview x positions, offset to one side (+1 = north/left)"""
    c0 = ch_of((x0, y_at_px(x0))); c1 = ch_of((x1, y_at_px(x1)))
    left, right = [], []
    n = max(2, int((c1 - c0) / step) + 1)
    for k in range(n):
        p, t = at(c0 + (c1 - c0) * k / (n - 1)); nx, ny = -t[1] * side, t[0] * side
        left.append([round(p[0] + nx * off, 2), round(p[1] + ny * off, 2)])
        right.append([round(p[0] + nx * (off + depth), 2), round(p[1] + ny * (off + depth), 2)])
    return left + right[::-1]
def y_at_px(x):
    for (ax, ay), (bx, by) in zip(ROAD_PX, ROAD_PX[1:]):
        if ax <= x <= bx: return ay + (by - ay) * (x - ax) / (bx - ax)
    return ROAD_PX[-1][1]
def band(a, b, w):
    a, b = M(a), M(b); dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy); nx, ny = -dy / L * w / 2, dx / L * w / 2
    return [[a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny], [b[0] - nx, b[1] - ny], [a[0] - nx, a[1] - ny]]
def heading_at(px, reverse=False):
    p, t = at(ch_of(px)); h = math.degrees(math.atan2(t[1], t[0]))
    return round(h + (180 if reverse else 0), 1)

site = dict(name='โครงการด่านตรวจ 5 จุด (ระบบไม้กั้นและ LPR)', notes='Generated by make_site.py from the client drawings.')
site['streets'] = [
    dict(id='CHT', label='ถนนจตุรทิศ', polygon=band((420, 100), (262, 420), 35)),
    dict(id='KP7', label='ถนนกำแพงเพชร 7', polygon=band((930, 495), (1470, 252), 20)),
    dict(id='PBR', label='ถนนเพชรบุรีตัดใหม่', polygon=band((900, 560), (1470, 320), 32)),
    dict(id='R9', label='ถนนพระราม 9', polygon=band((20, 25), (260, 75), 22)),
]
site['water'] = [dict(id='KSS', label='คลองสามเสน', polygon=band((90, 318), (340, 140), 14))]
site['roads'] = [dict(id='MAIN', label='ถนนภายในโครงการ', points=ROAD, width=ROAD_W),
                 dict(id='LINK2', label='ถนนเชื่อมจุดที่ 2', points=Ms([(972, 356), (972.6, 400), (972.6, 485)]), width=13.5)]

# buildings (north = yellow office blocks, south = shophouse rows), heights are typical, not surveyed
B = []
north = [('A', 215, 300, 20), ('B', 425, 520, 22), ('C', 530, 640, 20), ('D', 650, 745, 20), ('IF', 785, 850, 12),
         ('E', 885, 950, 18), ('F', 990, 1095, 20), ('G', 1105, 1170, 20), ('H', 1215, 1395, 14)]
for name, x0, x1, h in north:
    B.append(dict(id=f'B{name}', label=('Bldg ' + name) if name != 'IF' else 'IF Bldg', polygon=strip(x0, x1, 1, 9, 22 if name != 'H' else 12), height=h))
for k, (x0, x1) in enumerate([(150, 290), (395, 470), (480, 560), (570, 650), (660, 740), (750, 830), (840, 905)]):
    B.append(dict(id=f'S{k + 1}', label=f'อาคารพาณิชย์ {k + 1}', polygon=strip(x0, x1, -1, 9, 11), height=10))
B.append(dict(id='OFF', label='Office Main', polygon=Ms([(925, 382), (962, 382), (962, 440), (948, 440), (925, 405)]), height=20))
B.append(dict(id='NIA', label='NIA Place', polygon=Ms([(990, 368), (1130, 362), (995, 440)]), height=15))
site['buildings'] = B

# checkpoints: template chosen from the matching drawing; heading = IN direction (into the campus)
p4 = at(ch_of((761.4, 341.6)))[0]; p5 = at(ch_of((864.5, 347.6)))[0]
nN = lambda px: (lambda t: (-t[1], t[0]))(at(ch_of(px))[1])
def north_of(px, d):
    p, t = at(ch_of(px)); return [round(p[0] - t[1] * d, 2), round(p[1] + t[0] * d, 2)]
site['gate_kits'] = [
    dict(id='G1', label='จุดที่ 1 ป้อมจตุรทิศ', template='T1323', pos=M((375.8, 271.7)), heading=heading_at((375.8, 271.7)), apron=24),
    dict(id='G2', label='จุดที่ 2 ป้อมเพชรบุรี', template='T1323', pos=M((972.6, 443.2)), heading=90.0, apron=24,
         faults={'ขาเข้า ช่อง 2': 'fault'}),
    dict(id='G3', label='จุดที่ 3 ป้อมทางออกศูนย์วิจัย', template='T1060', pos=at(ch_of((1184.5, 313.3)))[0], heading=heading_at((1184.5, 313.3), True), apron=22),
    dict(id='G4', label='จุดที่ 4 ป้อม I-HOUSE (A,B,C)', template='T794', pos=north_of((761.4, 341.6), 20),
         heading=round(heading_at((761.4, 341.6)) + 90, 1), apron=15),
    dict(id='G5', label='จุดที่ 5 ป้อม I-HOUSE (C,D)', template='T884', pos=north_of((864.5, 347.6), 20),
         heading=round(heading_at((864.5, 347.6)) + 90, 1), apron=15),
]
for k in site['gate_kits']:
    k['pos'] = [round(k['pos'][0], 2), round(k['pos'][1], 2)]
# driveways from the main road into the I-House gates
site['roads'] += [dict(id='DW4', label='ทางเข้า I-HOUSE (A,B,C)', points=[[round(p4[0], 2), round(p4[1], 2)], north_of((761.4, 341.6), 36)], width=8.5),
                  dict(id='DW5', label='ทางเข้า I-HOUSE (C,D)', points=[[round(p5[0], 2), round(p5[1], 2)], north_of((864.5, 347.6), 36)], width=9.4)]
site['faults_note'] = 'G2 lane IN-2 marked faulty as a demo'
# I-House forecourts behind gates 4 and 5 (paved, no stall layout: not on the drawing)
def plaza(px, d0, depth, width):
    p, t = at(ch_of(px)); nx, ny = -t[1], t[0]
    c = [p[0] + nx * d0, p[1] + ny * d0]
    return [[round(c[0] + t[0] * s * width / 2 + nx * dd, 2), round(c[1] + t[1] * s * width / 2 + ny * dd, 2)] for s, dd in ((-1, 0), (1, 0), (1, depth), (-1, depth))]
site['parking_areas'] = [dict(id='IH1', label='ลาน I-HOUSE (A,B,C)', polygon=plaza((761.4, 341.6), 35, 26, 34), no_stalls=True),
                         dict(id='IH2', label='ลาน I-HOUSE (C,D)', polygon=plaza((864.5, 347.6), 35, 26, 34), no_stalls=True)]

# control room (Bldg B) + uplink cable routes along the north kerb of the road
cr = north_of((472, 292), 12); site['control_room'] = dict(pos=cr, label='Control Room (ชั่วคราว)')
def route(px_to, extra=None, off=6.0):
    c0 = ch_of((472, 292)); c1 = ch_of(px_to); pts = []
    n = max(2, int(abs(c1 - c0) / 8) + 1)
    for k in range(n):
        p, t = at(c0 + (c1 - c0) * k / (n - 1)); pts.append([round(p[0] - t[1] * off, 2), round(p[1] + t[0] * off, 2)])
    pts = [cr] + pts + (extra or [])
    return pts, round(sum(math.dist(a, b) for a, b in zip(pts, pts[1:])))
cab = []
for gid, px, extra, col, off in (('G1', (375.8, 271.7), None, [.1, .3, .95], 6.0),
                                 ('G4', (761.4, 341.6), [north_of((761.4, 341.6), 20)], [.9, .1, .1], 6.6),
                                 ('G5', (864.5, 347.6), [north_of((864.5, 347.6), 20)], [.1, .1, .6], 7.2),
                                 ('G3', (1184.5, 313.3), None, [.85, .1, .85], 7.8),
                                 ('G2', (972, 356), [M((978, 400)), M((978, 443.2))], [.1, .7, .2], 8.4)):
    pts, L = route(px, extra, off)
    cab.append(dict(id=f'UL_{gid}', to=gid, label=f'UPLink → {gid} ≈ {L} ม.', length_m=L, points=pts, color=col, width=.35))
site['cables'] = cab
site['trees'] = []
json.dump(site, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'site.json'), 'w', encoding='utf8'), ensure_ascii=False, indent=1)
